"""Renders the model read by ``schema`` as Python source."""

from __future__ import annotations

import re
import textwrap
from dataclasses import dataclass
from typing import Any

from tools.gen.profiles import Profile
from tools.gen.schema import EnumIR, FieldIR, MessageIR, ModelIR, SchemaIR

HEADER = "# Code generated by tools/gen. DO NOT EDIT."

# A sample is a JSON value rendered as source:
# ("lit", text) | ("dict", [(key, sample)]) | ("list", [..]).
Sample = tuple[Any, ...]


def member_name(value: str, overrides: dict[str, str]) -> str:
    """``Sample.Clock`` -> ``SAMPLE_CLOCK``; ``L1-N`` -> ``L1_N``."""
    if value in overrides:
        return overrides[value]
    parts = re.split(r"[.\-_ ]", value)
    words = [
        w
        for part in parts
        for w in re.split(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])", part)
    ]
    return "_".join(words).upper()


# -- samples -----------------------------------------------------------------


def _render(node: Sample, indent: int, lead: int = 0, width: int = 66) -> str:
    """Pretty-print a sample, breaking lines that would pass ``width``."""
    kind = node[0]
    if kind == "lit":
        return str(node[1])
    flat = _flat(node)
    if indent + lead + len(flat) <= width:
        return flat
    pad = " " * (indent + 4)
    if kind == "dict":
        inner = "".join(f'{pad}"{k}": {_render(v, indent + 4, len(k) + 4)},\n' for k, v in node[1])
        return f"{{\n{inner}{' ' * indent}}}"
    items = node[1]
    inner = "".join(f"{pad}{_render(v, indent + 4)},\n" for v in items)
    return f"[\n{inner}{' ' * indent}]"


def _flat(node: Sample) -> str:
    kind = node[0]
    if kind == "lit":
        return str(node[1])
    if kind == "dict":
        return "{" + ", ".join(f'"{k}": {_flat(v)}' for k, v in node[1]) + "}"
    return f"[{', '.join(_flat(v) for v in node[1])}]"


@dataclass
class _Ctx:
    profile: Profile
    ir: SchemaIR

    def model(self, name: str) -> ModelIR:
        if name in self.ir.types:
            return self.ir.types[name]
        for m in self.ir.messages:
            for r in (m.request, m.response):
                if r.name == name:
                    return r
        raise KeyError(name)

    def sample(self, f: FieldIR) -> Sample:
        if f.kind == "str":
            return ("lit", '"x"')
        if f.kind == "uri":
            return ("lit", '"https://example.com/f"')
        if f.kind == "datetime":
            return ("lit", '"2025-01-02T03:04:05Z"')
        if f.kind == "int":
            return ("lit", str(self.profile.sample_ints.get(f.wire, max(1, f.ge or 0))))
        if f.kind == "number":
            return ("lit", "1.5")
        if f.kind == "bool":
            return ("lit", "False")
        if f.kind == "enum":
            assert f.ref is not None
            return ("lit", f'"{self.ir.enums[f.ref].values[0]}"')
        if f.kind == "object":
            assert f.ref is not None
            return self.to_dict(self.model(f.ref))
        assert f.item is not None
        return ("list", [self.sample(f.item)])

    def to_dict(self, m: ModelIR) -> Sample:
        return ("dict", [(f.wire, self.sample(f)) for f in m.fields if f.required])


# -- fields ------------------------------------------------------------------


def _scalar(f: FieldIR) -> str:
    return {
        "str": "StrictStr",
        "uri": "AbsoluteURI",
        "datetime": "DateTime",
        "int": "StrictInt",
        "number": "OneDecimal" if f.one_decimal else "Number",
        "bool": "StrictBool",
    }.get(f.kind) or str(f.ref)


def _item_type(f: FieldIR) -> str:
    base = _scalar(f)
    if f.kind == "str" and f.max_length is not None:
        return f"Annotated[StrictStr, StringConstraints(max_length={f.max_length})]"
    return base


def _annotation(f: FieldIR) -> tuple[str, list[str]]:
    """The type annotation and the ``Field(...)`` arguments of a field."""
    args: list[str] = []
    if f.kind == "array":
        assert f.item is not None
        base = f"list[{_item_type(f.item)}]"
        if f.min_items is not None:
            args.append(f"min_length={f.min_items}")
    else:
        base = _scalar(f)
        if f.kind == "str":
            if f.non_empty:
                args.append("min_length=1")
            if f.max_length is not None:
                args.append(f"max_length={f.max_length}")
        elif f.kind in ("uri", "datetime") and f.max_length is not None:
            args.append(f"max_length={f.max_length}")
        if f.ge is not None:
            args.append(f"ge={f.ge}")
    return base, args


def _field_line(f: FieldIR) -> str:
    base, args = _annotation(f)
    if f.required:
        rhs = f" = Field({', '.join(args)})" if args else ""
        return f"{f.attr}: {base}{rhs}"
    return f"{f.attr}: {base} | None = Field({', '.join(['default=None', *args])})"


def _field_doc(f: FieldIR) -> str:
    bits = ["Required." if f.required else "Optional."]
    if f.kind == "array":
        assert f.item is not None
        bits.append(f"A list of {f.item.ref or f.item.kind}.")
        if f.min_items:
            bits.append(f"At least {f.min_items} item{'s' if f.min_items > 1 else ''}.")
    elif f.ref:
        bits.append(f"A ``{f.ref}``.")
    elif f.kind == "datetime":
        bits.append("A timestamp.")
    elif f.kind == "uri":
        bits.append("An absolute URI.")
    elif f.kind == "number" and f.one_decimal:
        bits.append("At most one fractional digit.")
    if f.max_length is not None:
        bits.append(f"At most {f.max_length} characters.")
    if f.ge is not None:
        bits.append(f"At least {f.ge}.")
    return f"{f.attr}: {' '.join(bits)}"


# -- classes -----------------------------------------------------------------


def _doc(summary: str, fields: list[FieldIR], example: list[str], indent: str = "    ") -> str:
    lines = [summary]
    if fields:
        lines += ["", "Attributes:"]
        lines += [f"    {_field_doc(f)}" for f in fields]
    lines += ["", "Example:", *(f"    {e}" for e in example)]
    body = "\n".join(f"{indent}{ln}".rstrip() for ln in lines)
    return f'{indent}"""{body.lstrip()}\n{indent}"""'


def _doctest(name: str, expr: Sample) -> list[str]:
    """``>>>`` lines assigning ``value = <name>.model_validate(<sample>)``."""
    text = _render(expr, indent=0, lead=len(name) + 25)
    first, *rest = (f"value = {name}.model_validate({text})").split("\n")
    return [f">>> {first}", *(f"... {r}" for r in rest)]


def _rules(m: ModelIR) -> list[str]:
    if not m.rules:
        return []
    body = textwrap.indent(textwrap.dedent(m.rules).strip("\n"), "        ")
    return [
        "",
        '    @model_validator(mode="after")',
        "    def _check_rules(self) -> Self:",
        body,
        "        return self",
    ]


def _model_class(m: ModelIR, ctx: _Ctx, *, message: bool) -> str:
    sample = ctx.to_dict(m)
    if message:
        example = [*_doctest(m.name, sample), ">>> value.ACTION", f"'{m.action}'"]
    else:
        example = [*_doctest(m.name, sample), ">>> type(value).__name__", f"'{m.name}'"]
    summary = m.doc or f"The {m.name} datatype."
    out = [f"class {m.name}(OCPPModel):", _doc(summary, m.fields, example)]
    if message:
        out.append(f'    ACTION: ClassVar[str] = "{m.action}"')
        out.append("")
    for f in m.fields:
        out.append(f"    {_field_line(f)}")
    if not m.fields and not message:
        out.append("    pass")
    out += _rules(m)
    return "\n".join(out)


def _enum_class(e: EnumIR, profile: Profile) -> str:
    names = [member_name(v, profile.member_names) for v in e.values]
    if len(set(names)) != len(names):
        raise ValueError(f"{e.name}: member names clash: {names}")
    first, name = e.values[0], names[0]
    example = [f'>>> {e.name}("{first}").name', f"'{name}'"]
    out = [f"class {e.name}(StrEnum):", _doc(e.doc, [], example)]
    out += [f'    {n} = "{v}"' for n, v in zip(names, e.values, strict=True)]
    return "\n".join(out)


_IMPORTS = """\
from enum import StrEnum
from typing import Annotated, ClassVar, Self

from pydantic import Field, StrictBool, StrictInt, StrictStr, StringConstraints, model_validator

from ocpp_sdk.model import AbsoluteURI, DateTime, Number, OCPPModel, OneDecimal
from ocpp_sdk.model import needed_error, rule_error
"""


def _sorted_all(names: list[str]) -> str:
    """``__all__`` in the order ruff's RUF022 wants: CONSTANTS, then Classes, then others."""

    def key(name: str) -> tuple[int, str]:
        group = 0 if name.isupper() else 1 if name[0].isupper() else 2
        return (group, name)

    return repr(sorted(names, key=key))


def _names(profile: Profile, ir: SchemaIR) -> list[str]:
    return sorted({*ir.enums, *ir.types})


def render_types(profile: Profile, ir: SchemaIR) -> str:
    """The shared datatypes and enums module."""
    ctx = _Ctx(profile, ir)
    parts = [
        HEADER,
        f'"""Datatypes and enumerations shared by the OCPP {profile.version} messages."""\n',
        _IMPORTS,
        f"__all__ = {_sorted_all([*ir.enums, *ir.types])}\n",
    ]
    parts += [_enum_class(e, profile) + "\n" for e in ir.enums.values()]
    parts += [_model_class(m, ctx, message=False) + "\n" for m in ir.types.values()]
    return "\n\n".join(parts)


def render_module(profile: Profile, ir: SchemaIR, module: str, title: str) -> str:
    """One feature profile's messages."""
    ctx = _Ctx(profile, ir)
    messages: list[MessageIR] = [m for m in ir.messages if m.module == module]
    classes = [c for m in messages for c in (m.request, m.response)]
    shared = ", ".join(_names(profile, ir))
    pairs = ",\n    ".join(f"({m.request.name}, {m.response.name})" for m in messages)
    parts = [
        HEADER,
        f'"""OCPP {profile.version} {title} messages."""\n',
        _IMPORTS,
        f"from {_package(profile)}.types import {shared}\n",
        f"__all__ = {_sorted_all(['MESSAGES', *(c.name for c in classes)])}\n",
    ]
    for m in messages:
        parts.append(_model_class(m.request, ctx, message=True) + "\n")
        parts.append(_model_class(m.response, ctx, message=True) + "\n")
    parts.append(
        "MESSAGES: tuple[tuple[type[OCPPModel], type[OCPPModel]], ...] = (\n"
        f"    {pairs},\n)\n"
        '"""Every request and response pair of this module, for the registry."""\n'
    )
    return "\n\n".join(parts)


def _package(profile: Profile) -> str:
    return f"ocpp_sdk.{profile.package}"
